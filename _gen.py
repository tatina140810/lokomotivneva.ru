def crumbs(*items):
    # items: list of (label, href|None)
    out = []
    for label, href in items:
        if href:
            out.append(f'<li><a href="{href}">{label}</a></li>')
        else:
            out.append(f'<li aria-current="page">{label}</li>')
    return "".join(out)

