def build():
    for route, d in PAGES.items():
        html = (TPL
                .replace("{{TITLE}}", d["title"])
                .replace("{{DESC}}", d["desc"])
                .replace("{{CRUMB}}", d["crumb"])
                .replace("{{H1}}", d["h1"])
                .replace("{{LEAD}}", d["lead"])
                .replace("{{BODY}}", d["body"]))
        outdir = os.path.join(ROOT, route)
        os.makedirs(outdir, exist_ok=True)
        with open(os.path.join(outdir, "index.html"), "w", encoding="utf-8") as f:
            f.write(html)
        print("written:", route + "/index.html")

if __name__ == "__main__":
    build()
    print("done:", len(PAGES), "pages")
